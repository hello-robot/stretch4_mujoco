"""Paint Stretch 4's gripper fingers and their ArUco tags to match the real tools.

Each fingertip on both the SG4 and the PG4 carries a flat 18 mm pad for an
ArUco tag. The URDF ships the pad as a bare white mesh; `write_aruco_tag`
projects the real marker onto it, generated by OpenCV from the same dictionary
and ID the robot's detectors look for.

The PG4 finger is one STL holding several CAD shells: the black base block
with its slide carriage, pin and carriage screws, the blue fin-ray, the steel
screws holding the fin-ray into the base block, and a thin black grip strip
skinned over the fin-ray's inner face and around its tip.
`split_parallel_gripper_finger` sorts those shells into a blue, a black and a
steel mesh so each can carry its own colour.

The SG4 fingertip is one STL holding two shells: the black pad and the white
holder the ArUco tag sits on. `split_standard_gripper_fingertip` separates them.
"""

from __future__ import annotations

from pathlib import Path
from typing import NamedTuple

import cv2
import numpy as np
import trimesh

# The detectors in stretch4_ai and stretch_core use this dictionary, and the
# real fingertips carry these IDs (decoded off a wrist camera frame).
ARUCO_DICTIONARY = cv2.aruco.DICT_6X6_250
ARUCO_MARKER_IDS = {"left": 200, "right": 201}

# Edge of the black marker, measured off the real fingertip: it fills ~78% of
# the 18 mm white pad, the rest being the white quiet zone.
ARUCO_MARKER_SIZE = 0.014
# Texels per marker bit. A 6x6 marker plus its one-bit border is 8 bits wide.
ARUCO_PIXELS_PER_BIT = 32
ARUCO_MARKER_BITS = 8

# The wrist camera frame the tags are oriented against: on the real tools each
# marker reads upright in this camera.
GRIPPER_CAMERA_FRAME = "gripper_left_camera_color_optical_frame"

# A PG4 finger shell belongs to the fin-ray end if it comes within this
# distance of the fingertip. The base block stops ~55 mm short of it.
TIP_TOLERANCE = 0.002

# The grip strip runs the full length of the fin-ray's inner face, then wraps
# around the tip and back along the outer face for this fraction of the
# fin-ray's exposed length, i.e. from the tip to the base block's front face.
STRIP_WRAP_FRACTION = 0.2
# The strip's grip-face section lies within this depth of the grip plane;
# strip geometry deeper than this is the wrap onto the outer face.
STRIP_FACE_DEPTH = 0.001

# The PG4 finger's screws all run along its Z axis. A bore is a concave ring of
# wall faces within ~6 degrees of vertical, at least BORE_MIN_FACES strong, and
# round to within BORE_MAX_RADIUS_STD.
BORE_WALL_MAX_NZ = 0.1
BORE_MIN_FACES = 20
BORE_MAX_RADIUS_STD = 0.0003
BORE_MIN_RADIUS = 0.0008
BORE_MAX_RADIUS = 0.003
# A shell is a screw when it is centred, in X and Y, within this distance of a
# bore's axis. Socket screws carry their own bore, the hex socket.
SCREW_COAXIAL_TOLERANCE = 0.0005


class FingerParts(NamedTuple):
    """
    A PG4 finger mesh split by colour, in the finger frame.

    Attributes:
        fin_ray: The blue fin-ray.
        black: The base block, slide carriage, pin and carriage screws, and the
            grip strip.
        screws: The steel screws holding the fin-ray, or None if there are none.
    """

    fin_ray: trimesh.Trimesh
    black: trimesh.Trimesh
    screws: trimesh.Trimesh | None


def aruco_image(marker_id: int, pad_size: float) -> np.ndarray:
    """
    Render an ArUco marker centred on a white pad.

    Args:
        marker_id: Marker ID in ARUCO_DICTIONARY.
        pad_size: Edge of the square pad in metres; the marker is
            ARUCO_MARKER_SIZE across and the remainder is white margin.

    Returns:
        The pad as an RGB uint8 image, marker top at row 0.
    """
    dictionary = cv2.aruco.getPredefinedDictionary(ARUCO_DICTIONARY)
    marker_px = ARUCO_MARKER_BITS * ARUCO_PIXELS_PER_BIT
    marker = cv2.aruco.generateImageMarker(dictionary, marker_id, marker_px, borderBits=1)

    pad_px = int(round(marker_px * pad_size / ARUCO_MARKER_SIZE))
    before = (pad_px - marker_px) // 2
    after = pad_px - marker_px - before
    pad = cv2.copyMakeBorder(
        marker, before, after, before, after, cv2.BORDER_CONSTANT, value=255
    )
    return cv2.cvtColor(pad, cv2.COLOR_GRAY2RGB)


def marker_right_axis(R_camera_tag: np.ndarray) -> np.ndarray:
    """
    The tag-frame direction that the marker's rightward edge runs along.

    The tag lies in its link's XY plane, facing +Z. The camera's image-right
    axis is expressed in the tag frame and snapped to the nearest of +/-X and
    +/-Y, since the marker is printed square to the pad's edges.

    Args:
        R_camera_tag: Rotation of the tag link in GRIPPER_CAMERA_FRAME.

    Returns:
        A unit vector along +/-X or +/-Y of the tag frame.
    """
    # Row 0 of R_camera_tag is the camera's X axis in the tag frame.
    image_right = R_camera_tag[0, :2]
    axis = int(np.argmax(np.abs(image_right)))
    right = np.zeros(3)
    right[axis] = np.sign(image_right[axis])
    return right


def write_aruco_tag(
    stl_path: str | Path,
    obj_path: str | Path,
    png_path: str | Path,
    marker_id: int,
    right: np.ndarray,
) -> None:
    """
    Project an ArUco marker onto a fingertip tag pad.

    Every vertex is projected along the tag's +Z onto the pad image, so the top
    face carries the marker and the side walls take the white margin.

    Args:
        stl_path: The tag pad mesh, flat in its XY plane and facing +Z.
        obj_path: Where to write the pad with texture coordinates.
        png_path: Where to write the marker texture.
        marker_id: Marker ID in ARUCO_DICTIONARY.
        right: Tag-frame unit vector the marker's rightward edge runs along,
            from `marker_right_axis`.

    Returns:
        None.
    """
    mesh = trimesh.load(stl_path, process=True)
    centre = mesh.bounds.mean(0)
    pad_size = float(mesh.extents[:2].max())
    up = np.cross([0.0, 0.0, 1.0], right)

    offset = np.asarray(mesh.vertices) - centre
    # MuJoCo samples textures with v = 0 at the bottom of the image, so the
    # marker's top edge is v = 1.
    uv = np.stack([0.5 + offset @ right / pad_size, 0.5 + offset @ up / pad_size], 1)

    with open(obj_path, "w") as f:
        f.write("# Stretch 4 fingertip ArUco tag, generated by gripper_texture.py\n")
        np.savetxt(f, mesh.vertices, fmt="v %.6f %.6f %.6f")
        np.savetxt(f, uv, fmt="vt %.6f %.6f")
        idx = np.repeat(np.asarray(mesh.faces) + 1, 2, axis=1)
        np.savetxt(f, idx, fmt="f %d/%d %d/%d %d/%d")

    cv2.imwrite(str(png_path), cv2.cvtColor(aruco_image(marker_id, pad_size), cv2.COLOR_RGB2BGR))


def _slice(mesh: trimesh.Trimesh, normal: list[float], origin: list[float]) -> trimesh.Trimesh:
    """
    Keep the part of an open mesh on the positive side of a plane.

    Args:
        mesh: The mesh to cut.
        normal: Plane normal, pointing into the part kept.
        origin: Any point on the plane, in metres.

    Returns:
        The kept part, without a cap over the cut.
    """
    return trimesh.intersections.slice_mesh_plane(mesh, normal, origin, cap=False)


def _find_bores(part: trimesh.Trimesh) -> list[tuple[np.ndarray, float, float, float]]:
    """
    Find the round holes running along Z through one shell.

    Args:
        part: One shell of a finger mesh.

    Returns:
        Each bore's axis (x, y), outer radius, and lowest and highest Z, in metres.
    """
    wall = np.abs(part.face_normals[:, 2]) < BORE_WALL_MAX_NZ
    adjacency = part.face_adjacency[wall[part.face_adjacency].all(axis=1)]
    rings = trimesh.graph.connected_components(
        adjacency, nodes=np.nonzero(wall)[0], min_len=BORE_MIN_FACES
    )

    bores = []
    for ring in rings:
        vertices = part.vertices[np.unique(part.faces[ring])]
        axis = vertices[:, :2].mean(0)
        r = np.linalg.norm(vertices[:, :2] - axis, axis=1)
        # A hole's walls face its axis; a boss's or a pin's face away from it.
        inward = np.einsum(
            "ij,ij->i", axis - part.triangles_center[ring, :2], part.face_normals[ring, :2]
        )
        if (
            BORE_MIN_RADIUS < r.mean() < BORE_MAX_RADIUS
            and r.std() < BORE_MAX_RADIUS_STD
            and (inward > 0).all()
        ):
            bores.append((axis, float(r.max()), vertices[:, 2].min(), vertices[:, 2].max()))
    return bores


def _is_steel_screw(
    part: trimesh.Trimesh, bore_axes: list[np.ndarray], pilot_axes: list[np.ndarray]
) -> bool:
    """
    Whether a base shell is one of the steel screws driven into the fin-ray.

    Args:
        part: One shell behind the fin-ray.
        bore_axes: (x, y) axes of every bore in the shells behind the fin-ray.
        pilot_axes: (x, y) axes of the fin-ray's pilot holes.

    Returns:
        True if the shell is centred on both a bore and a pilot hole.
    """
    centre = part.bounds.mean(axis=0)[:2]

    def on_any(axes: list[np.ndarray]) -> bool:
        """
        Whether the shell's centre lies on any of the given axes.

        Args:
            axes: (x, y) axes, in metres.

        Returns:
            True if one is within SCREW_COAXIAL_TOLERANCE of the centre.
        """
        return any(np.linalg.norm(centre - axis) < SCREW_COAXIAL_TOLERANCE for axis in axes)

    return on_any(bore_axes) and on_any(pilot_axes)


def split_parallel_gripper_finger(stl_path: str | Path) -> FingerParts:
    """
    Split a PG4 finger mesh into its blue fin-ray, its black parts and its steel screws.

    In the finger frame the grip plane is the +X face and the finger runs
    along Y from the tip, at the end nearer Y = 0, back to the base block.
    The black part is the base block with everything behind it, plus the grip
    strip trimmed to STRIP_WRAP_FRACTION over the tip. The steel screws are
    the shells behind the fin-ray that sit in a bore over one of its pilot
    holes; the carriage's screws have no pilot hole beneath and stay black.

    Args:
        stl_path: The PG4 finger_{left,right}_link visual mesh.

    Returns:
        The finger's parts, in the finger frame.
    """
    mesh = trimesh.load(stl_path, process=True)
    (_, y_min, _), (grip_x, y_max, _) = mesh.bounds

    # +1 when the finger runs from its tip towards +Y, -1 towards -Y.
    back = float(np.sign(mesh.bounds.mean(0)[1]))
    tip_y = y_min if back > 0 else y_max

    def tip_distance(part: trimesh.Trimesh) -> float:
        """
        Distance along the finger from the tip to a shell's nearest point.

        Args:
            part: One shell of the finger mesh.

        Returns:
            The distance in metres.
        """
        return float(((part.vertices[:, 1] - tip_y) * back).min())

    parts = mesh.split(only_watertight=False)
    tip_parts = [p for p in parts if tip_distance(p) < TIP_TOLERANCE]
    base_parts = [p for p in parts if tip_distance(p) >= TIP_TOLERANCE]
    if not tip_parts or not base_parts:
        raise ValueError(f"{stl_path} does not split into a fin-ray and a base block.")

    fin_ray = max(tip_parts, key=lambda p: len(p.faces))
    strip = trimesh.util.concatenate([p for p in tip_parts if p is not fin_ray])

    exposed = min(tip_distance(p) for p in base_parts)
    wrap_y = tip_y + back * STRIP_WRAP_FRACTION * exposed
    split_x = grip_x - STRIP_FACE_DEPTH

    strip_face = _slice(strip, [1.0, 0.0, 0.0], [split_x, 0.0, 0.0])
    strip_wrap = _slice(strip, [-1.0, 0.0, 0.0], [split_x, 0.0, 0.0])
    strip_wrap = _slice(strip_wrap, [0.0, -back, 0.0], [0.0, wrap_y, 0.0])

    pilot_axes = [axis for axis, *_ in _find_bores(fin_ray)]
    bore_axes = [axis for part in base_parts for axis, *_ in _find_bores(part)]
    steel = [p for p in base_parts if _is_steel_screw(p, bore_axes, pilot_axes)]
    black_parts = [p for p in base_parts if not any(p is screw for screw in steel)]

    black = trimesh.util.concatenate(
        [p for p in (*black_parts, strip_face, strip_wrap) if len(p.faces)]
    )
    screws = trimesh.util.concatenate(steel) if steel else None
    return FingerParts(fin_ray, black, screws)


def split_standard_gripper_fingertip(
    stl_path: str | Path, tag_position: np.ndarray
) -> tuple[trimesh.Trimesh, trimesh.Trimesh]:
    """
    Split an SG4 fingertip mesh into its ArUco tag holder and its pad.

    The holder is the shell whose bounding box lies nearest the tag; every
    other shell is the pad.

    Args:
        stl_path: The SG4 gripper_fingertip_{left,right}_link visual mesh.
        tag_position: The tag link's origin in the fingertip frame, in metres.

    Returns:
        The holder mesh and the pad mesh, in the fingertip frame.
    """
    mesh = trimesh.load(stl_path, process=True)
    parts = mesh.split(only_watertight=False)
    if len(parts) < 2:
        raise ValueError(f"{stl_path} does not split into a tag holder and a pad.")

    def box_distance(part: trimesh.Trimesh) -> float:
        """
        Distance from the tag to a shell's bounding box, zero inside it.

        Args:
            part: One shell of the fingertip mesh.

        Returns:
            The distance in metres.
        """
        low, high = part.bounds
        outside = np.maximum(low - tag_position, tag_position - high)
        return float(np.linalg.norm(np.maximum(0.0, outside)))

    holder = min(parts, key=box_distance)
    pad = trimesh.util.concatenate([p for p in parts if p is not holder])
    return holder, pad
